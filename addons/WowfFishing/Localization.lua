local clientLocale = GetLocale()
local clientLanguage = (clientLocale == "zhCN" or clientLocale == "zhTW") and "zh" or "en"
local language = clientLanguage
local widgetLabels = {}
local L = setmetatable({}, {
    __index = function(_, key)
        return (language == "en" and english[key]) or key
    end,
})
addon.L = L

function addon.SetLocalizedText(widget, key)
    widgetLabels[widget] = key
    widget:SetText(L[key])
end

function addon.InitializeLocale(preference)
    language = (preference == "zh" or preference == "en") and preference or clientLanguage
    for widget, key in pairs(widgetLabels) do
        widget:SetText(L[key])
    end
end

function addon.IsEnglish()
    return language == "en"
end

function addon.PreferClientNames()
    return (language == "zh" and clientLocale == "zhCN")
        or (language == "en" and (clientLocale == "enUS" or clientLocale == "enGB"))
end
